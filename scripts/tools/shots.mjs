import { chromium } from '/home/claude/kalpi-negisha/node_modules/playwright/index.mjs';
const out = process.argv[2];
const b = await chromium.launch({ executablePath: '/tmp/chromium', args: ['--no-sandbox','--no-zygote'] });
const p = await b.newPage({ viewport: { width: 400, height: 900 }, deviceScaleFactor: 1 });
await p.goto('http://127.0.0.1:4174/he/');
await p.waitForSelector('#f-locality');
await p.screenshot({ path: `${out}/1-search-he.png`, fullPage: true });
await p.locator('#f-locality').selectOption({ label: 'בדיקה-א' });
await p.locator('form.search button[type=submit]').click();
await p.waitForTimeout(400);
await p.screenshot({ path: `${out}/2-results-he.png`, fullPage: true });
await p.getByRole('link', { name: 'አማርኛ' }).click();
await p.waitForTimeout(400);
await p.screenshot({ path: `${out}/3-results-am.png`, fullPage: true });
await b.close();
